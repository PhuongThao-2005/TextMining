def normalize_language(value: str | None) -> str:
    return value if value in LANGUAGE_OPTIONS else "vi"


def t(lang: str, key: str, **kwargs: Any) -> str:
    value = _COPY.get(normalize_language(lang), _COPY["vi"]).get(key, _COPY["en"].get(key, key))
    return value.format(**kwargs) if kwargs else value


def theme_label(lang: str, value: str) -> str:
    key = {
        "System": "theme_system",
        "Light": "theme_light",
        "Dark": "theme_dark",
    }.get(value)
    return t(lang, key) if key else value


